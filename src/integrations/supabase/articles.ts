import { supabase } from './client';

// Base type for an article, aligning with your database schema
export type Article = {
  id: string;
  slug: string;
  title: string;
  content: string;
  excerpt: string;
  author_name: string;
  author_email: string;
  author_social: { [key: string]: string };
  cover_image?: string;
  published_at: string;
  status: 'draft' | 'pending_review' | 'approved' | 'rejected';
  category: 'Medicine' | 'Dental' | 'Pharmacy';
};

// A leaner type for public-facing article cards for performance
export type ArticleCard = Pick<Article, 'id' | 'slug' | 'title' | 'excerpt' | 'author_name' | 'cover_image' | 'published_at'>;

// Type for a single comment
export type Comment = {
    id: string;
    display_name?: string | null;
    content: string;
    created_at: string;
};

// --- PUBLIC-FACING FUNCTIONS ---

/**
 * Fetches all *approved* articles for the public list view.
 */
export const getApprovedArticles = async (): Promise<ArticleCard[]> => {
  const { data, error } = await supabase
    .from('articles')
    .select('id, slug, title, excerpt, author_name, cover_image, published_at')
    .eq('status', 'approved')
    .order('published_at', { ascending: false });

  if (error) {
    console.error('Error fetching approved articles:', error);
    throw new Error(error.message);
  }

  return data || [];
};

/**
 * Fetches a single article by its slug.
 * By default, it only fetches approved articles.
 * Admins can set `isAdmin` to true to fetch articles of any status.
 */
export const getArticleBySlug = async (slug: string, isAdmin = false): Promise<Article | null> => {
  let query = supabase
    .from('articles')
    .select('*')
    .eq('slug', slug);

  if (!isAdmin) {
    query = query.eq('status', 'approved');
  }

  const { data, error } = await query.single();

  if (error && error.code !== 'PGRST116') { // Ignore 'No rows found'
    console.error('Error fetching article by slug:', error);
    throw new Error(error.message);
  }

  return data;
};

/**
 * Fetches all comments for a given article ID.
 */
export const getCommentsByArticleId = async (articleId: string): Promise<Comment[]> => {
    const { data, error } = await supabase
        .from('comments')
        .select('id, display_name, content, created_at')
        .eq('article_id', articleId)
        .order('created_at', { ascending: false });

    if (error) throw new Error(error.message);
    return data || [];
};

/**
 * Creates a new anonymous comment for an article.
 */
export const createComment = async (articleId: string, content: string, displayName?: string): Promise<Comment> => {
    const { data, error } = await supabase
        .from('comments')
        .insert({ article_id: articleId, content, display_name: displayName || null })
        .select()
        .single();

    if (error) throw new Error(error.message);
    return data;
};

// --- ADMIN-ONLY FUNCTIONS ---

/**
 * [ADMIN] Fetches all articles, regardless of status.
 */
export const getAllArticles = async (): Promise<Article[]> => {
  const { data, error } = await supabase
    .from('articles')
    .select('*')
    .order('published_at', { ascending: false });

  if (error) throw new Error(error.message);
  return data || [];
};

// Type for the article form data, omitting fields generated by the DB.
export type ArticleFormData = Omit<Article, 'id'>;

/**
 * [ADMIN] Creates a new article.
 */
export const createArticle = async (articleData: ArticleFormData): Promise<Article> => {
  const { data, error } = await supabase
    .from('articles')
    .insert(articleData)
    .select()
    .single();

  if (error) {
    console.error("Supabase error creating article:", error);
    throw new Error(error.message);
  }
  return data;
};

/**
 * [ADMIN] Updates an existing article by its original slug.
 */
export const updateArticle = async (originalSlug: string, articleData: Partial<ArticleFormData>): Promise<Article> => {
  const { data, error } = await supabase
    .from('articles')
    .update(articleData)
    .eq('slug', originalSlug)
    .select()
    .single();

  if (error) {
    console.error("Supabase error updating article:", error);
    throw new Error(error.message);
  }
  return data;
};

/**
 * [ADMIN] Deletes an article by its ID.
 */
export const deleteArticle = async (id: string): Promise<void> => {
  const { error } = await supabase
    .from('articles')
    .delete()
    .eq('id', id);

  if (error) {
    console.error("Supabase error deleting article:", error);
    throw new Error(error.message);
  }
};
