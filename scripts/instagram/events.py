# ───────── tiny document DSL (TipTap JSON) ─────────
def t(s):
    return {"type": "text", "text": s}


def b(s):
    return {"type": "text", "text": s, "marks": [{"type": "bold"}]}


def p(*parts):
    return {"type": "paragraph", "content": [t(x) if isinstance(x, str) else x for x in parts]}


def h(s, level=2):
    return {"type": "heading", "attrs": {"level": level}, "content": [t(s)]}


def ul(*items):
    return {"type": "bulletList", "content": [{"type": "listItem", "content": [p(*i) if isinstance(i, tuple) else p(i)]} for i in items]}


def callout(tone, *paras):
    return {"type": "callout", "attrs": {"tone": tone, "color": None}, "content": [p(x) if isinstance(x, str) else x for x in paras]}


def gal(keys, layout="grid", columns=3):
    return {"type": "gallery", "attrs": {"images": keys, "layout": layout, "columns": columns}}


def img(key, width="100"):
    return {"type": "image", "attrs": {"src": key, "width": width}}


def vid(key, title="", caption="", poster=None):
    return {"type": "video", "attrs": {"provider": "file", "src": key, "poster": poster or f"{key}-poster", "title": title, "caption": caption}}


